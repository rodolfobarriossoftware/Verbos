const MODO_ESTRICTO = false;

// =====================================================
//  LÓGICA DEL JUEGO
// =====================================================
let words = [];
let wordsPendientes = [];
let wordsAciertos = [];
let actual = null;
let esperando = false;         // true = mostrando el error, Enter para continuar
let categoriaActual = TODO;

const elVerbo = document.getElementById("verbo");
const elInput = document.getElementById("respuesta");
const elResultado = document.getElementById("resultado");

// --- Interfaz extra creada desde JS (no hace falta tocar el HTML) ---
elInput.placeholder = "Escribe en inglés";

const selector = document.createElement("select");
